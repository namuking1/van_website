export function routePath(language, slug = '') {
  return `/${language}/${slug ? `${slug}/` : ''}`
}

export function basePath(pathname) {
  const base = import.meta.env.BASE_URL === '/' ? '' : import.meta.env.BASE_URL.replace(/\/$/, '')
  return `${base}${pathname}`
}
